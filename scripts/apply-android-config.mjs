/**
 * Re-applies this project's Gradle configuration to the generated Android
 * project, after `npx cap add android` has scaffolded it.
 *
 * android/ is generated output and is gitignored, so hand-editing
 * android/app/build.gradle is not an option — the next `cap add` discards it.
 * This script re-applies the wiring on every build instead.
 *
 * The approach mirrors Expo's own EAS integration: write a self-contained
 * .gradle file next to build.gradle and append a single `apply from:` line,
 * rather than pattern-matching the template's `android { }` block. One appended
 * line is stable across Capacitor template changes; a regex over the block is
 * not. The script is idempotent.
 *
 * Two things are applied:
 *
 *   1. The release signing config. Capacitor's template sets NO signingConfig on
 *      the release build type at all, so without this the build emits
 *      app-release-unsigned.apk.
 *   2. versionCode / versionName, which Capacitor does not take from
 *      capacitor.config.json and which would otherwise be the template's
 *      1 / "1.0".
 *
 * No credentials pass through this script, through capacitor.config.json, or
 * through any generated file. The emitted Gradle reads two environment variables
 * that hold *paths*, and loads the passwords from the properties file at Gradle
 * execution time. Under the Docker build those paths point at BuildKit secret
 * mounts, so the secrets exist only for the duration of one RUN and never enter
 * an image layer.
 *
 * If either variable is unset the signing wiring stands down and the template's
 * unsigned-release default remains in force, so a local `gradlew assembleRelease`
 * still works on a machine with no keystore.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const APP_DIR = join(ROOT, 'android', 'app');

const GRADLE_FILE = 'hulaan-bayan.gradle';
const APPLY_LINE = `apply from: "./${GRADLE_FILE}"`;

/** Env var holding the path to the keystore itself. */
export const ENV_KEYSTORE = 'HULAAN_RELEASE_KEYSTORE';
/** Env var holding the path to the properties file with the passwords. */
export const ENV_PROPERTIES = 'HULAAN_RELEASE_KEYSTORE_PROPERTIES';

/**
 * Printed by Gradle when the release keystore is actually picked up. The Docker
 * build greps for it, so signing wiring that silently fails to apply fails the
 * build rather than yielding an unsigned or debug-signed "release" APK.
 */
export const MARKER_ACTIVE = 'HULAAN-SIGNING: release keystore active';
const MARKER_INACTIVE = 'HULAAN-SIGNING: no keystore configured, release will be UNSIGNED';

const VERSION_CODE = 1;
const VERSION_NAME = '1.0.0';

const GRADLE_SCRIPT = `// Generated by scripts/apply-android-config.mjs — do not edit.
// android/ is regenerated by \`npx cap add android\`; edits here are discarded.

android {
    defaultConfig {
        versionCode ${VERSION_CODE}
        versionName "${VERSION_NAME}"
    }
}

def keystorePath = System.getenv("${ENV_KEYSTORE}")
def propertiesPath = System.getenv("${ENV_PROPERTIES}")

if (keystorePath && propertiesPath && file(keystorePath).exists() && file(propertiesPath).exists()) {
    def creds = new Properties()
    file(propertiesPath).withInputStream { creds.load(it) }

    def storePw = creds.getProperty("storePassword")
    def alias = creds.getProperty("keyAlias")
    // PKCS12 keystores have no separate key password; Gradle still demands one,
    // and the store password satisfies it.
    def keyPw = creds.getProperty("keyPassword") ?: storePw

    if (!storePw || !alias) {
        throw new GradleException(
            "\${propertiesPath} must define storePassword and keyAlias")
    }

    android {
        signingConfigs {
            release {
                storeFile file(keystorePath)
                storePassword storePw
                keyAlias alias
                keyPassword keyPw
            }
        }
        buildTypes {
            release {
                signingConfig signingConfigs.release
            }
        }
    }

    logger.lifecycle("${MARKER_ACTIVE} (\${keystorePath}, alias \${alias})")
} else {
    logger.lifecycle("${MARKER_INACTIVE}")
}
`;

const fail = (message) => {
  console.error(`\nFATAL: ${message}\n`);
  process.exit(1);
};

const buildGradlePath = join(APP_DIR, 'build.gradle');
if (!existsSync(buildGradlePath)) {
  fail(`${buildGradlePath} not found. Run \`npx cap add android\` first.`);
}

// --- Write the gradle file the apply line points at -------------------------
writeFileSync(join(APP_DIR, GRADLE_FILE), GRADLE_SCRIPT);
console.log(`  wrote   android/app/${GRADLE_FILE}`);

// --- Append the apply line, unless it is already there ----------------------
const contents = readFileSync(buildGradlePath, 'utf8');
const already = contents
  .split('\n')
  .some((line) => line.trim() === APPLY_LINE || line.trim() === APPLY_LINE.replace(/"/g, "'"));

if (already) {
  console.log(`  ok      android/app/build.gradle already applies ${GRADLE_FILE}`);
} else {
  writeFileSync(buildGradlePath, `${contents.trimEnd()}\n\n${APPLY_LINE}\n`);
  console.log(`  wired   android/app/build.gradle -> ${APPLY_LINE}`);
}

console.log(`  version versionCode ${VERSION_CODE}, versionName ${VERSION_NAME}`);
console.log(
  process.env[ENV_KEYSTORE]
    ? `  signing ${ENV_KEYSTORE} is set; release will be signed`
    : `  signing ${ENV_KEYSTORE} is unset; release would be UNSIGNED (expected outside the release build)`
);
